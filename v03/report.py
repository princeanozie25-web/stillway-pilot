"""Build results/v03/tables.md from the result files.   python v03/report.py"""
import glob, json, os, statistics as st

R = "results/v03"; out = []
def P(*a): out.append(" ".join(str(x) for x in a))
def load(p): return json.load(open(p)) if os.path.exists(p) else None
def pct(x, d=1): return "–" if x is None else f"{100 * x:.{d}f}%"
def mean(xs): xs = [x for x in xs if x is not None]; return sum(xs) / len(xs) if xs else None
ARMS = [("v3r23", "T23, discrete carry"), ("v3r23fix", "T23, repaired (same)"), ("v3r24", "T24x, discrete carry"), ("v3r24fix", "T24x, repaired (all)"),
        ("v3c23", "T23, free-vector carry"), ("v3c24", "T24x, free-vector carry"), ("v3n23", "T23, no value-table aid"), ("v3n24", "T24x, no value-table aid"),
        ("v3o", "T24x, outcomes only (exploratory)")]
def seeds(arm, mode): return sorted(glob.glob(f"{R}/{mode}/{arm}_s?.json"))

# ---- F1 ------------------------------------------------------------------------------------------------
P("# v0.3 result tables\n\nGenerated by `v03/report.py` from the files in `results/v03/`. Means are over core seeds; n = number of seeds.\n")
P("## F1. The v0.2 final items (frozen v0.2 harness and seed; 4,000 flip attempts per stratum per core)\n")
P("Joint edit success, non-trivial eligible attempts. v0.2 rows are copied from `results/v02/m3/`.\n")
P("| Cores | n | Method | A unseen families | B four legs | C cross-gate | Pooled |"); P("|---|---|---|---|---|---|---|")
def pooled(d, m):
    e = [d["strata"][s][m]["eligible"] for s in d["strata"]]; j = [d["strata"][s][m]["joint_success"] * d["strata"][s][m]["eligible"] for s in d["strata"]]
    return sum(j) / max(1, sum(e))
v2 = [load(f) for f in sorted(glob.glob("results/v02/m3/v2_iit_s?_final.json"))]
for m, lab in (("editor:predictor", "predictor edit"), ("message", "message")):
    P(f"| v0.2 cores (T23) | {len(v2)} | {lab} | " + " | ".join(pct(mean([d['strata'][s][m]['joint_success'] for d in v2])) for s in ("A_unseen_families", "B_four_legs", "C_cross_gate")) + f" | {pct(mean([pooled(d, m) for d in v2]))} |")
for arm, lab in ARMS:
    ds = [load(f) for f in seeds(arm, "v02final")]
    if not ds: continue
    for m, ml in (("editor", "register write"), ("message", "message"), ("restart", "restart")):
        P(f"| {lab} | {len(ds)} | {ml} | " + " | ".join(pct(mean([d['strata'][s][m]['joint_success'] for d in ds])) for s in ("A_unseen_families", "B_four_legs", "C_cross_gate")) + f" | {pct(mean([pooled(d, m) for d in ds]))} |")
P("\nPlanner alone on the same strata (share of jobs with every action valid, ordinary events):\n")
P("| Cores | n | A | B | C |"); P("|---|---|---|---|---|")
ca = load("results/v02/m3/core_accuracy_final.json")
if ca: P("| v0.2 cores (T23) | 5 | " + " | ".join(pct(mean([ca[f'v2_iit_s{i}'][s]['with_events'] for i in range(1, 6)])) for s in ("A_unseen_families", "B_four_legs", "C_cross_gate")) + " |")
for arm, lab in ARMS:
    ds = [load(f) for f in seeds(arm, "v02final")]
    if ds: P(f"| {lab} | {len(ds)} | " + " | ".join(pct(mean([d['strata'][s]['planner_alone']['with_events']['jobs_all_valid'] for d in ds]), 2) for s in ("A_unseen_families", "B_four_legs", "C_cross_gate")) + " |")
P("\nSecondary cells and shortcuts, register write on the T23 cores (mean over seeds):\n")
ds = [load(f) for f in seeds("v3r23", "v02final")]
if ds:
    keys = [k for k in ds[0]["strata"]["A_unseen_families"] if k != "planner_alone"]
    P("| Cell | A | B | C |"); P("|---|---|---|---|")
    for k in keys:
        key = "pairs_both_right" if k.startswith("mirror") else "joint_success"
        P(f"| {k} | " + " | ".join(pct(mean([d['strata'][s][k][key] for d in ds])) for s in ("A_unseen_families", "B_four_legs", "C_cross_gate")) + " |")
    P("\nUnrelated obligations (register write, T23 cores): largest drop against the unedited replay over strata and seeds: "
      + pct(max(d['strata'][s]['editor']['unrelated_drop'] for d in ds for s in d['strata']), 2) + ". Abstentions: "
      + pct(max(d['strata'][s]['editor']['abstained'] for d in ds for s in d['strata']), 2) + ".")

# ---- F2 ------------------------------------------------------------------------------------------------
STR = ["S_2to3", "S_4", "S_5to6", "S_7to8", "S_12", "S_16", "X_2to4", "X_5to6", "X_7to8", "X_12", "X_16"]
P("\n## F2. Long jobs (final family buckets, v0.3 final seed; 2,000 flip attempts per stratum per core)\n")
P("S = same-gate legs, X = cross-gate legs with probability 0.3. The number after the underscore is the number of legs.\n")
for title, getter, d_ in (("Planner alone: share of jobs with every action valid, ordinary events", lambda d, s: d["strata"][s]["planner_alone"]["with_events"]["jobs_all_valid"], 2),
                          ("Planner alone, stress events", lambda d, s: d["strata"][s]["planner_alone"]["stress_events"]["jobs_all_valid"], 2),
                          ("Register write: joint edit success", lambda d, s: d["strata"][s]["editor"]["joint_success"], 1),
                          ("Message and resume: joint edit success", lambda d, s: d["strata"][s]["message"]["joint_success"], 1)):
    P(f"**{title}**\n"); P("| Cores | n | " + " | ".join(STR) + " |"); P("|---|---|" + "---|" * len(STR))
    for arm, lab in ARMS:
        ds = [load(f) for f in seeds(arm, "final")]
        if ds: P(f"| {lab} | {len(ds)} | " + " | ".join(pct(mean([getter(d, s) for d in ds]), d_) for s in STR) + " |")
    P("")
P("**Per seed, planner alone with ordinary events: lowest stratum** (S strata for T23 cores, all strata for T24x cores)\n")
P("| Core | lowest stratum | value | passes 99% everywhere |"); P("|---|---|---|---|")
for arm, lab in ARMS[:4] + ARMS[8:]:
    for f in seeds(arm, "final"):
        d = load(f); ss = [s for s in STR if s.startswith("S")] if "23" in arm else STR
        v = {s: d["strata"][s]["planner_alone"]["with_events"]["jobs_all_valid"] for s in ss}; lo = min(v, key=v.get)
        P(f"| {d['run']} | {lo} | {pct(v[lo], 2)} | {'yes' if v[lo] >= 0.99 else 'no'} |")
P("\nShortcuts on the long strata (T24x repaired cores, mean joint success over strata and seeds): "
  + ", ".join(f"{m} {pct(mean([d['strata'][s][m]['joint_success'] for d in [load(f) for f in seeds('v3r24fix', 'final')] for s in STR]))}" for m in ("ignore", "original", "overwrite", "actioncopy")) + ".")
ds = [load(f) for f in seeds("v3r24fix", "final")]
if ds:
    def pool2(m): return sum(d["strata"][s][m]["joint_success"] * d["strata"][s][m]["eligible"] for d in ds for s in STR) / sum(d["strata"][s][m]["eligible"] for d in ds for s in STR)
    P(f"\nPooled over all eleven strata, T24x repaired cores: register write {pct(pool2('editor'), 2)}, message {pct(pool2('message'), 2)}, restart {pct(pool2('restart'), 2)}; "
      f"eligible attempts {sum(d['strata'][s]['editor']['eligible'] for d in ds for s in STR)}; largest unrelated drop {pct(max(d['strata'][s]['editor']['unrelated_drop'] for d in ds for s in STR), 2)}.")

# ---- certificates ----------------------------------------------------------------------------------------
P("\n## F3. Certificates (any number of legs)\n")
P("pairs = (code, exact value table) pairs in the closure; checks = pairs x leg kinds x gate states; margin = smallest gap between the two routes where only one is valid.\n")
P("| Core | Alphabet | Pairs | Depth | Codes | Checks | Wrong | Margin | Witnesses confirmed on the network | Simulator: wrong actions / action stages | Prediction holds |"); P("|---|---|---|---|---|---|---|---|---|---|---|")
for f in sorted(glob.glob(f"{R}/cert/*_s?.json")) + sorted(glob.glob(f"{R}/cert_o/*_s?.json")):
    d = load(f); cf = load(f"{R}/confirm/{d['run']}.json")
    for a in ("same", "all"):
        c = d[a]; w = c["witness_replays"]; s = cf[a] if cf else None
        P(f"| {d['run']} | {a} | {c['pairs']} | {c['closure_depth']} | {c['codes_used']} | {c['route_checks']} | {c['route_wrong']} | {c['min_margin'].get('route_when_one_route_is_valid')} | "
          f"{sum(r['network_wrong'] for r in w)} of {len(w)} | " + (f"{s['wrong_actions']} / {s['action_stages']} | {'yes' if s['prediction_holds'] else 'NO'} |" if s else "– | – |"))
P("\nRepair rounds (wrong entries in the closure before each round):\n")
P("| Core | Clean | Wrong by round | Gradient steps | Longest witness job |"); P("|---|---|---|---|---|")
for r in sorted(glob.glob("runs/v3r2*fix*_s?")):
    m = load(r + "/manifest.json")
    if m: P(f"| {m['name']} | {'yes' if m['clean'] else 'no'} | {', '.join(str(x['route_wrong']) for x in m['repair_rounds'])} | {m['repair_gradient_steps']} | {m['longest_witness_job_legs']} legs |")
P("\nFree-vector carry (no codes, so no certificate): simulator only.\n")
P("| Core | Alphabet | Wrong actions / action stages | Jobs with a wrong action |"); P("|---|---|---|---|")
for f in sorted(glob.glob(f"{R}/confirm/v3c*.json")):
    d = load(f)
    for a in ("same", "all"): P(f"| {d['run']} | {a} | {d[a]['wrong_actions']} / {d[a]['action_stages']} | {d[a]['jobs_with_a_wrong_action']} of {d[a]['jobs']} |")

# ---- latency ---------------------------------------------------------------------------------------------
P("\n## F5. Revision latency (median microseconds, one job, one CPU thread)\n")
P("| Core | Legs | Network, message | Network, register write | Certified tables, register write | Exact planner, plain Python |"); P("|---|---|---|---|---|---|")
for f in sorted(glob.glob(f"{R}/latency/*.json")):
    d = load(f)
    for L in ("3_legs", "16_legs"):
        x = d[L]; P(f"| {d['run']} | {L.split('_')[0]} | {x['network_message']['median_us']} | {x['network_register_write']['median_us']} | {x['tables_register_write']['median_us']} | {x['symbolic']['median_us']} |")

# ---- arm M -----------------------------------------------------------------------------------------------
P("\n## Arm M. Canonical memory by training rule alone (v0.2 core, development families, 20,000 jobs per cell)\n")
P("| Core | K (wait slots per leg) | Task success | Distinct saved states | Distinct meanings | Sampled dictionary knows (steps of fresh jobs) |"); P("|---|---|---|---|---|---|")
for name in ["v2_iit_s1", "v2x_canon_s1"] + [f"v3m_s{i}" for i in (1, 2, 3)]:
    d = load(f"{R}/scaling/{name}.json") or load(f"results/v02/scaling/{name}.json")
    if not d: continue
    for k, c in d["history"].items():
        P(f"| {name} | {k.split('=')[1]} | {pct(c['task_success'], 2)} | {c['distinct_states']} | {c['distinct_meanings']} | {pct(c['coverage_of_steps_fresh_jobs'], 1)} |")
for name in [f"v3m_s{i}" for i in (1, 2, 3)]:
    d = load(f"{R}/m_dev/{name}_dev.json")
    if d:
        s = d["strata"]["dev"]; e = d["editors"]
        P(f"\n{name}, development edit attempts: message {pct(s['message']['joint_success'])}, slot write {pct(s['editor:slot_write']['joint_success'])} (abstained {pct(s['editor:slot_write']['abstained'])}), "
          f"predictor {pct(s['editor:predictor']['joint_success'])}; codes known per slot {e.get('slot_known_codes')}.")
os.makedirs(R, exist_ok=True); open(f"{R}/tables.md", "w").write("\n".join(out) + "\n"); print("wrote", f"{R}/tables.md", len(out), "lines")
